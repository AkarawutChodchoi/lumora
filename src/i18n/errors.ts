const ENTITY_TH: Record<string, string> = {
  Character: "ตัวละคร",
  Conversation: "แชต",
  Memory: "ความจำ",
  Message: "ข้อความ",
  User: "ผู้ใช้",
  Report: "รายงาน",
  Appeal: "คำอุทธรณ์",
  Enforcement: "คำตัดสิน",
  Generation: "คำตอบ",
  Resource: "ข้อมูล",
};

/** Localize a server message. Unknown messages fall back to English (or a generic Thai one for validation). */
export function localizeMessage(message: string, locale: Locale, opts: { validation?: boolean } = {}): string {
  if (locale === "en") return message;
  if (TH[message]) return TH[message];
  const nf = message.match(/^(\w+) not found$/);
  if (nf) return `ไม่พบ${ENTITY_TH[nf[1]] ?? "ข้อมูล"}`;
  const rl = message.match(/^Too many requests\. Try again in (\d+)s\.$/);
  if (rl) return `ส่งคำขอบ่อยเกินไป ลองใหม่ในอีก ${rl[1]} วินาที`;
  return opts.validation ? "ข้อมูลในช่องนี้ไม่ถูกต้อง" : message;
}
